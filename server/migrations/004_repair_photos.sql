-- Repair photos. The image files live on disk in PHOTOS_DIR (its own Docker
-- volume); this table only records them.
CREATE TABLE IF NOT EXISTS repair_photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Set to NULL when the repair is deleted but its photos are kept (archived).
  repair_id bigint REFERENCES repairs(id) ON DELETE SET NULL,
  -- Copied so archived photos still say which repair and customer they came from.
  repair_number text NOT NULL,
  customer_name text,
  file_name text NOT NULL UNIQUE,
  thumb_name text,
  original_name text,
  content_type text NOT NULL,
  size integer NOT NULL,
  thumb_size integer NOT NULL DEFAULT 0,
  caption text,
  uploaded_by bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- When the repair was deleted and its photos were kept.
  archived_at timestamptz
);
CREATE INDEX IF NOT EXISTS repair_photos_repair_id_idx ON repair_photos(repair_id);
